using JuMP

model = Model()

@variable(model, x1, start = -8)
@variable(model, x2, start = -8)
@variable(model, objvar)
@variable(model, 0 <= x4 <= 50, start = 1)
@variable(model, 0 <= x5 <= 50)
@variable(model, 0 <= x6 <= 200)
@variable(model, 0 <= x7 <= 200)
@variable(model, 0 <= x8 <= 200)
@variable(model, 0 <= x9 <= 200)
@variable(model, 0 <= x10 <= 200)
@variable(model, 0 <= x11 <= 200)
@variable(model, 0 <= x12 <= 200)
@variable(model, 0 <= x13 <= 200)
@variable(model, 0 <= x14 <= 200)
@variable(model, 0 <= x15 <= 200)
@variable(model, 0 <= x16 <= 200)
@variable(model, 0 <= x17 <= 200)

@objective(model, Min, objvar)

@constraint(model, - 3*x1 - 3*x2 - objvar + 2*x4 + 2*x5 == 60)
@constraint(model, x1 - 2*x2 + x4 + x5 <= 40)
@constraint(model, 2*x1 - x4 + x6 == -10)
@constraint(model, 2*x2 - x5 + x7 == -10)
@constraint(model, - x1 + x8 == 10)
@constraint(model, x1 + x9 == 20)
@constraint(model, - x2 + x10 == 10)
@constraint(model, x2 + x11 == 20)
@constraint(model, x6*x12 == 0)
@constraint(model, x7*x13 == 0)
@constraint(model, x8*x14 == 0)
@constraint(model, x9*x15 == 0)
@constraint(model, x10*x16 == 0)
@constraint(model, x11*x17 == 0)
@constraint(model, 2*x1 - 2*x4 + 2*x12 - x14 + x15 == -40)
@constraint(model, 2*x2 - 2*x5 + 2*x13 - x16 + x17 == -40)
