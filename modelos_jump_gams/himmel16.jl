using JuMP

model = Model()

@variable(model, x1 == 0)
@variable(model, x2, start = 0.5)
@variable(model, x3, start = 0.5)
@variable(model, x4, start = 0.5)
@variable(model, x5)
@variable(model, x6)
@variable(model, x7 == 0)
@variable(model, x8 == 0)
@variable(model, x9, start = 0.4)
@variable(model, x10, start = 0.8)
@variable(model, x11, start = 0.8)
@variable(model, x12, start = 0.4)
@variable(model, x13)
@variable(model, x14)
@variable(model, x15)
@variable(model, x16)
@variable(model, x17)
@variable(model, x18)
@variable(model, objvar)

@objective(model, Min, objvar)

@constraint(model, (x1 - x2)^2 + (x7 - x8)^2 <= 1)
@constraint(model, (x1 - x3)^2 + (x7 - x9)^2 <= 1)
@constraint(model, (x1 - x4)^2 + (x7 - x10)^2 <= 1)
@constraint(model, (x1 - x5)^2 + (x7 - x11)^2 <= 1)
@constraint(model, (x1 - x6)^2 + (x7 - x12)^2 <= 1)
@constraint(model, (x2 - x3)^2 + (x8 - x9)^2 <= 1)
@constraint(model, (x2 - x4)^2 + (x8 - x10)^2 <= 1)
@constraint(model, (x2 - x5)^2 + (x8 - x11)^2 <= 1)
@constraint(model, (x2 - x6)^2 + (x8 - x12)^2 <= 1)
@constraint(model, (x3 - x4)^2 + (x9 - x10)^2 <= 1)
@constraint(model, (x3 - x5)^2 + (x9 - x11)^2 <= 1)
@constraint(model, (x3 - x6)^2 + (x9 - x12)^2 <= 1)
@constraint(model, (x4 - x5)^2 + (x10 - x11)^2 <= 1)
@constraint(model, (x4 - x6)^2 + (x10 - x12)^2 <= 1)
@constraint(model, (x5 - x6)^2 + (x11 - x12)^2 <= 1)
@constraint(model, - x13 - x14 - x15 - x16 - x17 - x18 - objvar == 0)
@constraint(model, - 0.5*(x1*x8 - x7*x2) + x13 == 0)
@constraint(model, - 0.5*(x2*x9 - x8*x3) + x14 == 0)
@constraint(model, - 0.5*(x3*x10 - x9*x4) + x15 == 0)
@constraint(model, - 0.5*(x4*x11 - x10*x5) + x16 == 0)
@constraint(model, - 0.5*(x5*x12 - x11*x6) + x17 == 0)
@constraint(model, - 0.5*(x6*x7 - x12*x1) + x18 == 0)
