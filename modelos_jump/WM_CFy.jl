@variable(model, alpha[1:Nu, 1:2])
@variable(model, x[0:N-1, 1:2])
@variable(model, z[0:N,   1:M])
@variable(model, y[0:2*N-1, 1:2])
@variable(model, t)

@objective(model, Min, t)

@constraint(model, bound31[j=N:2*N-1],
    -t * sqrt((1/N) * sum(y[i,1]^2 for i in N:2*N-1)) <= y[j,1])
@constraint(model, bound32[j=N:2*N-1],
    y[j,1] <= t * sqrt((1/N) * sum(y[i,1]^2 for i in N:2*N-1)))
@constraint(model, bound41[j=N:2*N-1],
    -t * sqrt((1/N) * sum(y[i,2]^2 for i in N:2*N-1)) <= y[j,2])
@constraint(model, bound42[j=N:2*N-1],
    y[j,2] <= t * sqrt((1/N) * sum(y[i,2]^2 for i in N:2*N-1)))
@constraint(model, bound51[j=N:2*N-1], y[j,1] <= bd)
@constraint(model, bound52[j=N:2*N-1], -bd <= y[j,1])
@constraint(model, bound61[j=N:2*N-1], y[j,2] <= bd)
@constraint(model, bound62[j=N:2*N-1], -bd <= y[j,2])

@constraint(model, inp1[i=0:N-1],
    x[i,1] == sum(a1[u] * cos(i * u * 2 * pi_val / N + alpha[u,1]) for u in 1:Nu))
@constraint(model, inp2[i=0:N-1],
    x[i,2] == sum(a2[u] * cos(i * u * 2 * pi_val / N + alpha[u,2]) for u in 1:Nu))

@constraint(model, out1[i=1:N, j=1:M],
    z[i,j] == sum(A[j,l] * z[i-1,l] for l in 1:M) +
               sum(B[j,l] * x[i-1,l] for l in 1:2))

@constraint(model, out2[i=1:N, j=1:2],
    y[i,j] == sum(C[j,l] * z[i,l] for l in 1:M))

@constraint(model, out3[i=N+1:2*N-1, j=1:2],
    y[i,j] == sum(C[j,l] * z[i-N-1,l] for l in 1:M))

@constraint(model, move1[i=0:N-2, j=1:2], -mx <= x[i+1,j] - x[i,j])
@constraint(model, move2[j=1:2],           -mx <= x[0,j] - x[N-1,j])
