S = union(-lim:0, 1:lim)
W = [(m1, m2) for m1 in S for m2 in S if !(m1 == 0 && m2 == 0)]

model = Model()

@variable(model, a1v[1:Nu])
@variable(model, a2v[1:Nu])
@variable(model, alpha[1:Nu, 1:2])
@variable(model, x[0:N-1, 1:2])
@variable(model, y[0:2*N-1, 1:2])

@objective(model, Min, 0)

@constraint(model, weyl1[(m1,m2) in W],
    sum(cos(2*pi_val*(m1*(y[n,1]+0.5) + m2*(y[n,2]+0.5))) for n in N:2*N-1) <= t)
@constraint(model, weyl2[(m1,m2) in W],
    sum(sin(2*pi_val*(m1*(y[n,1]+0.5) + m2*(y[n,2]+0.5))) for n in N:2*N-1) <= t)

@constraint(model, fix6[i=1:9], a1v[3*i] == a2v[3*i])
@constraint(model, bound51[j=N:2*N-1, i=1:2], -bdy <= y[j,i] <= bdy)

@constraint(model, inp1[i=0:N-1],
    x[i,1] == sum(a1v[u] * cos(pn[u] * (i+1) + alpha[u,1]) for u in 1:Nu))
@constraint(model, inp2[i=0:N-1],
    x[i,2] == sum(a2v[u] * cos(pn[u] * (i+1) + alpha[u,2]) for u in 1:Nu))

@constraint(model, out1[i=1:N, j=1:2],
    y[i,j] == alp * y[i-1,j] + (1-alp) * sum(kk[j,l] * x[i-1,l] for l in 1:2))
@constraint(model, out2[i=N+1:2*N-1, j=1:2],
    y[i,j] == alp * y[i-1,j] + (1-alp) * sum(kk[j,l] * x[i-N-1,l] for l in 1:2))

@constraint(model, move1[i=0:N-2, j=1:2], -mx <= x[i+1,j] - x[i,j])
