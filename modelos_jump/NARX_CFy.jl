model = Model()

@variable(model, alpha[1:Nu, 1:2])
@variable(model, phi[0:14, 0:2*N-1, 1:5])
@variable(model, x[-mo:2*N-1, 1:2])
@variable(model, y[-mo:2*N-1, 1:2])
@variable(model, t)

@objective(model, Min, t)

@constraint(model, bound31[j=N:2*N-1], -t <= y[j,1])
@constraint(model, bound32[j=N:2*N-1],  y[j,1] <= t)
@constraint(model, bound41[j=N:2*N-1], -t <= y[j,2])
@constraint(model, bound42[j=N:2*N-1],  y[j,2] <= t)

@constraint(model, xstart[i=-mo:-1, j=1:2], x[i,j] == 0)
@constraint(model, ystart[i=-mo:-1, j=1:2], y[i,j] == 0)
@constraint(model, pstart[i=0:2*N-1, j=1:4], phi[0,i,j] == 1)

@constraint(model, inp1_1[i=0:N-1],
    x[i,1] == sum(a1[u] * cos(i * u * 2 * pi_val / N + alpha[u,1]) for u in 1:Nu))
@constraint(model, inp1_2[i=0:N-1],
    x[i,2] == sum(a2[u] * cos(i * u * 2 * pi_val / N + alpha[u,2]) for u in 1:Nu))
@constraint(model, inp2[i=N:2*N-1, j=1:2], x[i,j] == x[i-N,j])

@constraint(model, p1[i=0:2*N-1, j=1:ny11],
    phi[1,i,j] == y[i-j,1])
@constraint(model, p2[i=0:2*N-1, j=1:ny22],
    phi[2,i,j] == y[i-j,2])
@constraint(model, p3[i=0:2*N-1, j=td1:td1+nu11],
    phi[3,i,j-td1+1] == x[i-j,1])
@constraint(model, p4[i=0:2*N-1, j=td2:td2+nu22],
    phi[4,i,j-td2+1] == x[i-j,2])
@constraint(model, p5[i=0:2*N-1, j=1:ny1, l=1:j],
    phi[5,i,(j-1)*j÷2+l] == y[i-j,1]*y[i-l,1])
@constraint(model, p6[i=0:2*N-1, j=1:ny2, l=1:j],
    phi[6,i,(j-1)*j÷2+l] == y[i-j,2]*y[i-l,2])
@constraint(model, p7[i=0:2*N-1, j=td1:td1+nu1, l=td1:j],
    phi[7,i,(j-td1)*(j-td1+1)÷2+l-td1+1] == x[i-j,1]*x[i-l,1])
@constraint(model, p8[i=0:2*N-1, j=td2:td2+nu2, l=td2:j],
    phi[8,i,(j-td2)*(j-td2+1)÷2+l-td2+1] == x[i-j,2]*x[i-l,2])
@constraint(model, p9[i=0:2*N-1, j=1:ny1, l=td1:td1+nu1],
    phi[9,i,(j-1)*(nu1+1)+l-td1+1] == y[i-j,1]*x[i-l,1])
@constraint(model, p10[i=0:2*N-1, j=1:ny1, l=td2:td2+nu2],
    phi[10,i,(j-1)*(nu2+1)+l-td2+1] == y[i-j,1]*x[i-l,2])
@constraint(model, p11[i=0:2*N-1, j=1:ny2, l=td1:td1+nu1],
    phi[11,i,(j-1)*(nu1+1)+l-td1+1] == y[i-j,2]*x[i-l,1])
@constraint(model, p12[i=0:2*N-1, j=1:ny2, l=td2:td2+nu2],
    phi[12,i,(j-1)*(nu2+1)+l-td2+1] == y[i-j,2]*x[i-l,2])
@constraint(model, p13[i=0:2*N-1, j=1:ny1, l=1:ny2],
    phi[13,i,(j-1)*ny2+l] == y[i-j,1]*y[i-l,2])
@constraint(model, p14[i=0:2*N-1, j=td1:td1+nu1, l=td2:td2+nu2],
    phi[14,i,(j-td1)*(nu2+1)+l-td2+1] == x[i-j,1]*x[i-l,2])

@constraint(model, out1_1[i=0:2*N-1],
    y[i,1] == sum(phi[kk,i,l] * theta1[offset[kk+1]+l]
                  for kk in 0:14 for l in 1:ind[kk+1]))
@constraint(model, out1_2[i=0:2*N-1],
    y[i,2] == sum(phi[kk,i,l] * theta2[offset[kk+1]+l]
                  for kk in 0:14 for l in 1:ind[kk+1]))

@constraint(model, move1[i=0:N-2, j=1:2], -mx <= x[i+1,j] - x[i,j])
@constraint(model, move2[j=1:2],           -mx <= x[0,j] - x[N-1,j])
@constraint(model, move3[i=0:N-2, j=1:2],  x[i+1,j] - x[i,j] <= mx)
@constraint(model, move4[j=1:2],            x[0,j] - x[N-1,j] <= mx)
@constraint(model, movey[ i=N-1:2*N-2, j=1:2], -my <= y[i+1,j] - y[i,j])
@constraint(model, movey1[i=N-1:2*N-2, j=1:2],  y[i+1,j] - y[i,j] <= my)
